    def extract_emails(lines):
        """
        Extract email addresses from markdown.

        Supports:
          - john@example.com
          - {alice,bob,charlie}@example.com
        """

        email_pattern = re.compile(
            r"[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}"
        )
        grouped_pattern = re.compile(
            r"\{([^{}]+)\}@([A-Za-z0-9.-]+\.[A-Za-z]{2,})"
        )
        emails = []
        for line in lines:
            # Expand grouped emails
            for names, domain in grouped_pattern.findall(line):
                for name in names.split(","):
                    name = normalize_string(name)
                    if name:
                        emails.append(f"{name}@{domain}")
            # Standard emails
            emails.extend(email_pattern.findall(line))
        seen = set()
        unique = []
        for email in emails:
            email = normalize_string(email)
            if email not in seen:
                seen.add(email)
                unique.append(email)
        return unique



