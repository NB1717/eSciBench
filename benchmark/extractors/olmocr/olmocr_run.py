def markdown_path(pdf) -> str:
    """
    Return the markdown path generated by OLMOCR for a PDF.
    """

    relative_pdf = pdf.filepath.lstrip("/")

    return os.path.join(
        OLMOCR_WORKSPACE,
        "markdown",
        os.path.splitext(relative_pdf)[0] + ".md",
    )

def normalize_equation(eq: str) -> str:
    eq = eq.replace(r"\left", "")
    eq = eq.replace(r"\right", "")
    eq = re.sub(r"\\mathrm\{([^{}]+)\}", r"\1", eq)

    eq = eq.replace(r"\sum", "∑")
    eq = eq.replace(r"\prod", "∏")
    eq = eq.replace(r"\int", "∫")
    eq = eq.replace(r"\phi", "φ")
    eq = eq.replace(r"\psi", "ψ")
    eq = eq.replace(r"\chi", "χ")
    eq = eq.replace(r"\xi", "ξ")
    eq = eq.replace(r"\delta", "δ")
    eq = eq.replace(r"\lambda", "λ")
    eq = eq.replace(r"\mu", "μ")
    eq = eq.replace(r"\pi", "π")
    eq = eq.replace(r"\sigma", "σ")
    eq = eq.replace(r"\gamma", "γ")
    eq = eq.replace(r"\omega", "ω")
    eq = eq.replace(r"\sqrt", "√")
    eq = eq.replace(r"\to", "→")
    eq = eq.replace(r"\cong", "≅")
    eq = eq.replace(r"\leq", "≤")
    eq = eq.replace(r"\geq", "≥")
    eq = eq.replace(r"\infty", "∞")
    eq = eq.replace(r"\sim", "∼")
    eq = eq.replace(r"\varphi", "φ")
    eq = eq.replace(r"\mapsto", "↦")
    eq = re.sub(r"\\xrightarrow\s*\{∼\}", "∼→", eq)
    
    eq = eq.replace(r"\#", "#")
    eq = eq.replace(r"\{", "{")
    eq = eq.replace(r"\}", "}")
    eq = eq.replace(r"\in", "∈")
    eq = eq.replace(r"\mid", "|")
    eq = eq.replace(r"\|", "∥")

    eq = eq.replace(r"\,", " ")
    eq = eq.replace(r"\!", "")
    eq = eq.replace(r"\:", " ")
    eq = eq.replace(r"\;", " ")
    eq = eq.replace(r"\quad", " ")
    eq = eq.replace(r"\qquad", " ")

    eq = re.sub(r"\s+", " ", eq).strip()

    return normalize_string(eq)


