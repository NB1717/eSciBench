        """
        Parse author / affiliation / email block before Abstract.
        """
        import re
        authors = []
        affiliations = []
        emails = []
        author_pattern = re.compile(
            r"^[A-Z][A-Za-z\.\-']+(?:\s+[A-Z][A-Za-z\.\-']+)+\*?$"
        )
        started = False
        current_author = False
        for line in lines:
            line = line.strip()
            if not started:
                if line:
                    started = True
                continue
            if line.lower() == "abstract":
                break
            if not line:
                continue
            # email
            if "@" in line:
                emails.append(normalize_string(line))
                current_author = False
                continue
            # every line after an author and before the email
            # belongs to the affiliation
            if current_author:
                 affiliations.append(normalize_string(line))

        return authors, affiliations, emails


